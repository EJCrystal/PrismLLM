package dev.soven.llmgateway.domain

import dev.soven.llmgateway.proxy.Usage

/** 一次智商检测的上游调用与判分结果。 */
data class IqTestRunRecord(
    val id: Long,
    val benchmark: String,
    val channelId: String,
    val channelName: String,
    val channelKeyId: String?,
    val channelKeyName: String?,
    val model: String,
    val upstreamModel: String,
    val protocol: String,
    val success: Boolean,
    val statusCode: Int?,
    val latencyMs: Long,
    val verdict: String,
    val prompt: String,
    val responseText: String?,
    val expectedAnswer: Int?,
    val matchedAnswer: Int?,
    val errorMessage: String?,
    val usage: Usage?,
    val upstreamReportedModel: String?,
    val judgeId: String?,
    val judgeLabel: String?,
    val judgeVerdict: String?,
    val judgeResultLabel: String?,
    val judgeReason: String?,
    val judgeScore: Double?,
    val judgeDetails: String?,
    val judgeCheckedAt: Long?,
    val manualVerdict: String?,
    val manualScore: Int?,
    val manualNote: String?,
    val manualUpdatedAt: Long?,
    val createdAt: Long,
)

/** 尚未分配数据库 id 的检测结果。 */
data class NewIqTestRun(
    val benchmark: String,
    val channelId: String,
    val channelName: String,
    val channelKeyId: String?,
    val channelKeyName: String?,
    val model: String,
    val upstreamModel: String,
    val protocol: String,
    val success: Boolean,
    val statusCode: Int?,
    val latencyMs: Long,
    val verdict: String,
    val prompt: String,
    val responseText: String?,
    val expectedAnswer: Int?,
    val matchedAnswer: Int?,
    val errorMessage: String?,
    val usage: Usage?,
    val upstreamReportedModel: String?,
    val judgeId: String?,
    val judgeLabel: String?,
    val judgeVerdict: String?,
    val judgeResultLabel: String?,
    val judgeReason: String?,
    val judgeScore: Double?,
    val judgeDetails: String?,
    val judgeCheckedAt: Long?,
    val manualVerdict: String? = null,
    val manualScore: Int? = null,
    val manualNote: String? = null,
    val manualUpdatedAt: Long? = null,
    val createdAt: Long = System.currentTimeMillis(),
)
